/**
 * Scans src/ for string literals that look like Material icon names
 * ("grid-view", "how-to-reg", ...) and writes src/ui/iconMap.generated.js
 * importing only those icons from react-icons/md.
 *
 *   npm run icons
 */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const md = require('react-icons/md');
const root = path.resolve(import.meta.dirname, '../src');

const walk = (d) =>
  fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(d, e.name);
    return e.isDirectory() ? walk(p) : /\.(jsx?|tsx?)$/.test(e.name) && !p.includes('.generated.') ? [p] : [];
  });

// Extra names to always include (aliases for icons whose legacy name differs)
const ALIASES = JSON.parse(fs.readFileSync(path.resolve(import.meta.dirname, 'icon-aliases.json'), 'utf8'));

const pascal = (n) => 'Md' + n.split('-').map((p) => p.charAt(0).toUpperCase() + p.slice(1)).join('');
const found = new Map();
for (const file of walk(root)) {
  const src = fs.readFileSync(file, 'utf8');
  for (const m of src.matchAll(/['"`]([a-z][a-z0-9]*(?:[-_][a-z0-9]+)*)['"`]/g)) {
    const name = m[1].replace(/_/g, '-');
    const comp = ALIASES[name] || pascal(name);
    if (md[comp]) found.set(name, comp);
  }
}
for (const [name, comp] of Object.entries(ALIASES)) if (md[comp]) found.set(name, comp);

const entries = [...found].sort(([a], [b]) => a.localeCompare(b));
const out =
  `// AUTO-GENERATED by scripts/generate-icons.mjs – do not edit.\n` +
  `import {\n${[...new Set(entries.map(([, c]) => `  ${c},`))].join('\n')}\n} from 'react-icons/md';\n\n` +
  `export default {\n${entries.map(([n, c]) => `  '${n}': ${c},`).join('\n')}\n};\n`;
fs.writeFileSync(path.join(root, 'ui/iconMap.generated.js'), out);
console.log(`Wrote ${entries.length} icons.`);

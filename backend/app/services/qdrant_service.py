import logging
import uuid
from typing import Any, Dict, List, Optional

from qdrant_client import QdrantClient
from qdrant_client.http import models as qmodels

from app.config import settings

logger = logging.getLogger("smart_campus.qdrant_service")


class QdrantVectorService:
    """
    Manages vector storage, indexing, and similarity search in Qdrant (Cloud / Local).
    Configured for 1024-dimensional multimodal vectors generated by Jina CLIP v2.
    """
    _instance: Optional["QdrantVectorService"] = None

    def __init__(self):
        self.endpoint = settings.qdrant_cluster_endpoint or settings.qdrant_host
        self.api_key = settings.qdrant_api_key or None
        self.client: Optional[QdrantClient] = None
        self.collection_name = settings.qdrant_collection_name
        self.vector_dim = settings.embedding_dim  # 1024

    @classmethod
    def get_instance(cls) -> "QdrantVectorService":
        if cls._instance is None:
            cls._instance = cls()
        return cls._instance

    def connect(self) -> QdrantClient:
        """Establishes or returns the existing connection to Qdrant."""
        if self.client is None:
            logger.info(f"Connecting to Qdrant at {self.endpoint}...")
            self.client = QdrantClient(
                url=self.endpoint,
                api_key=self.api_key,
                timeout=15.0,
                check_compatibility=False
            )
        return self.client

    def ensure_collection(
        self,
        collection_name: Optional[str] = None,
        vector_dim: Optional[int] = None
    ) -> bool:
        """
        Verifies if the specified collection exists. If not, creates it with Cosine distance.
        """
        target_collection = collection_name or self.collection_name
        target_dim = vector_dim or self.vector_dim
        client = self.connect()

        try:
            if client.collection_exists(target_collection):
                info = client.get_collection(target_collection)
                logger.info(
                    f"Qdrant collection '{target_collection}' ready with {info.points_count} points."
                )
                return True

            logger.info(
                f"Creating Qdrant collection '{target_collection}' with dim={target_dim}, distance=COSINE..."
            )
            client.create_collection(
                collection_name=target_collection,
                vectors_config=qmodels.VectorParams(
                    size=target_dim,
                    distance=qmodels.Distance.COSINE
                )
            )

            self._create_payload_indexes(target_collection)
            logger.info(f"Qdrant collection '{target_collection}' created successfully.")
            return True

        except Exception as exc:
            logger.warning(f"Qdrant collection notice: {exc}")
            return False

    def _create_payload_indexes(self, collection_name: str) -> None:
        """Creates keyword indexes for payload filtering."""
        client = self.connect()
        fields_to_index = ["modality", "category_id", "location_id", "record_id", "type"]
        for field in fields_to_index:
            try:
                client.create_payload_index(
                    collection_name=collection_name,
                    field_name=field,
                    field_schema=qmodels.PayloadSchemaType.KEYWORD
                )
            except Exception as e:
                logger.debug(f"Index creation note for field {field}: {e}")

    @staticmethod
    def generate_point_id(record_id: Any, modality: str) -> str:
        """
        Generates a stable, deterministic UUID5 for a given record_id and modality.
        """
        seed = f"campus:{str(record_id)}:{modality.lower()}"
        return str(uuid.uuid5(uuid.NAMESPACE_DNS, seed))

    def upsert_embedding(
        self,
        record_id: Any,
        modality: str,
        vector: List[float],
        description: Optional[str] = None,
        image_path: Optional[str] = None,
        category: Optional[str] = None,
        location: Optional[str] = None,
        created_at: Optional[str] = None,
        additional_metadata: Optional[Dict[str, Any]] = None,
        collection_name: Optional[str] = None
    ) -> Optional[str]:
        """
        Inserts or updates an embedding vector into Qdrant with campus metadata payload.
        """
        target_collection = collection_name or self.collection_name
        try:
            client = self.connect()
            point_id = self.generate_point_id(record_id, modality)

            payload = {
                "record_id": str(record_id),
                "modality": modality.lower(),
                "description": description,
                "image_path": image_path,
                "category": category,
                "location": location,
                "created_at": created_at,
            }

            if additional_metadata:
                payload.update(additional_metadata)

            # Strip None values
            payload = {k: v for k, v in payload.items() if v is not None}

            point = qmodels.PointStruct(
                id=point_id,
                vector=vector,
                payload=payload
            )

            client.upsert(
                collection_name=target_collection,
                points=[point]
            )
            logger.info(f"Upserted point {point_id} (record_id={record_id}, modality={modality}) into {target_collection}")
            return point_id
        except Exception as exc:
            logger.warning(f"Failed to upsert point to Qdrant: {exc}")
            return None

    def search_similar(
        self,
        query_vector: List[float],
        limit: int = 5,
        modality_filter: Optional[str] = None,
        category_filter: Optional[str] = None,
        location_filter: Optional[str] = None,
        type_filter: Optional[str] = None,
        score_threshold: Optional[float] = None,
        collection_name: Optional[str] = None
    ) -> List[Dict[str, Any]]:
        """
        Searches nearest vectors using cosine similarity with optional metadata filters.
        """
        target_collection = collection_name or self.collection_name
        try:
            client = self.connect()

            must_conditions = []
            if modality_filter:
                must_conditions.append(
                    qmodels.FieldCondition(
                        key="modality",
                        match=qmodels.MatchValue(value=modality_filter.lower())
                    )
                )
            if category_filter:
                must_conditions.append(
                    qmodels.FieldCondition(
                        key="category_id",
                        match=qmodels.MatchValue(value=str(category_filter))
                    )
                )
            if location_filter:
                must_conditions.append(
                    qmodels.FieldCondition(
                        key="location_id",
                        match=qmodels.MatchValue(value=str(location_filter))
                    )
                )
            if type_filter:
                must_conditions.append(
                    qmodels.FieldCondition(
                        key="type",
                        match=qmodels.MatchValue(value=str(type_filter).lower())
                    )
                )

            q_filter = qmodels.Filter(must=must_conditions) if must_conditions else None

            # Support query_points API
            if hasattr(client, "query_points"):
                response = client.query_points(
                    collection_name=target_collection,
                    query=query_vector,
                    query_filter=q_filter,
                    limit=limit,
                    score_threshold=score_threshold
                )
                points = response.points
            elif hasattr(client, "search"):
                points = client.search(
                    collection_name=target_collection,
                    query_vector=query_vector,
                    query_filter=q_filter,
                    limit=limit,
                    score_threshold=score_threshold
                )
            else:
                points = []

            results = []
            for p in points:
                results.append({
                    "id": p.id,
                    "score": p.score,
                    "payload": p.payload or {},
                    "record_id": (p.payload or {}).get("record_id"),
                })
            return results
        except Exception as exc:
            logger.warning(f"Qdrant similarity search notice: {exc}")
            return []


qdrant_service = QdrantVectorService.get_instance()
